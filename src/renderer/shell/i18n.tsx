const DICTS: Record<Lang, Dict> = { en: EN, ar: AR };

// BCP-47 locale per language, used for all Intl/date/number formatting. Arabic uses Egyptian
// formatting but with the Latin numbering system (`-u-nu-latn`) so prices, dates, and receipts show
// Western (0-9) digits — the retail convention here. Without the extension, ar-EG renders
// Arabic-Indic digits (٠-٩) under most ICU builds.
const LOCALES: Record<Lang, string> = { en: "en-US", ar: "ar-EG-u-nu-latn" };

/** Values substituted into `{name}`-style placeholders in a translated string. */
export type TVars = Record<string, string | number>;

function interpolate(template: string, vars?: TVars): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    key in vars ? String(vars[key]) : match,
  );
}

interface I18nValue {
  lang: Lang;
  dir: "ltr" | "rtl";
  locale: string;
  setLang: (lang: Lang) => void;
  toggleLang: () => void;
  t: (key: string, vars?: TVars) => string;
}

const I18nContext = createContext<I18nValue | null>(null);
const STORAGE_KEY = "pos.lang";

// Arabic is the primary language for this market, so a fresh install opens in Arabic (RTL). An
// explicit stored choice always wins and is remembered across sessions.
function initialLang(): Lang {
  if (typeof window === "undefined") return "ar";
  const stored = window.localStorage.getItem(STORAGE_KEY);
  return stored === "en" ? "en" : "ar";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang);
  const dir = lang === "ar" ? "rtl" : "ltr";
  const locale = LOCALES[lang];

  useEffect(() => {
    if (typeof document === "undefined") return;
    document.documentElement.lang = lang;
    document.documentElement.dir = dir;
    window.localStorage.setItem(STORAGE_KEY, lang);
  }, [lang, dir]);

  const setLang = useCallback((next: Lang) => setLangState(next), []);
  const toggleLang = useCallback(() => setLangState((l) => (l === "en" ? "ar" : "en")), []);
  const t = useCallback(
    (key: string, vars?: TVars) => interpolate(DICTS[lang][key] ?? DICTS.en[key] ?? key, vars),
    [lang],
  );

  const value = useMemo<I18nValue>(
    () => ({ lang, dir, locale, setLang, toggleLang, t }),
    [lang, dir, locale, setLang, toggleLang, t],
  );
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used within I18nProvider");
  return value;
}

export function useT(): (key: string, vars?: TVars) => string {
  return useI18n().t;
}
